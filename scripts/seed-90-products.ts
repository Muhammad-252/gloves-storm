async function runSeed() {
  console.log("🚀 Starting Full 90-Product Catalog Sync for GLOVES STORM...");
  console.log(`📡 Connected to Supabase Project: ${supabaseUrl}`);

  // 1. Check/Upsert Categories
  console.log("\n📁 Upserting 6 Official Categories...");
  const categoryMap = new Map<string, string>();

  for (const cat of CATEGORIES) {
    categoryMap.set(cat.slug, cat.id);
  }

  // Delete legacy products and categories to ensure clean 90-product sync
  console.log("🧹 Cleaning legacy catalog in Supabase...");
  await supabase.from("product_images").delete().neq("id", "00000000-0000-0000-0000-000000000000");
  await supabase.from("products").delete().neq("id", "00000000-0000-0000-0000-000000000000");
  await supabase.from("categories").delete().neq("id", "00000000-0000-0000-0000-000000000000");

  const { error: catInsertError } = await supabase.from("categories").insert(
    CATEGORIES.map((c) => ({
      id: c.id,
      name: c.name,
      slug: c.slug,
      description: c.description,
      image_url: c.image_url,
      sort_order: c.sort_order,
      is_active: true,
      parent_id: null,
    }))
  );

  if (catInsertError) {
    console.error("❌ Error inserting categories:", catInsertError);
    process.exit(1);
  }
  console.log(`✅ 6 Official Categories seeded.`);

  // 2. Prepare all 90 products
  console.log("\n📦 Preparing 90 Products with 360 High-Quality Images...");
  const dbProducts = [];
  const dbImages = [];
  const fullProductsForLocal = [];

  let pCounter = 1;
  for (const spec of CATALOG_SPECS) {
    const pId = `b0000001-0000-0000-0000-${String(pCounter).padStart(12, "0")}`;
    const categoryId = categoryMap.get(spec.categorySlug)!;
    const cat = CATEGORIES.find((c) => c.slug === spec.categorySlug)!;

    const shortDesc = spec.seoDescription;
    const fullDesc = `${spec.name} engineered and manufactured by GLOVES STORM in Sialkot, Pakistan. Designed for international brands, fight gyms, sports teams, and growing private labels requiring rigorous craftsmanship, consistent sizing, and premium materials. Fully customizable with your logo, brand colors, custom labeling, and retail-ready packaging.`;

    const productImages = getImagesForProduct(spec.categorySlug, spec.order, spec.name, pId, pCounter);

    const prodRecord = {
      id: pId,
      name: spec.name,
      slug: spec.slug,
      category_id: categoryId,
      short_description: shortDesc,
      description: fullDesc,
      materials: spec.materials,
      features: spec.features,
      customization_options: spec.customizationOptions.split(",").map((s) => s.trim()),
      moq: spec.moq,
      lead_time: spec.leadTime,
      featured: spec.featured || false,
      is_active: true,
      seo_title: spec.seoTitle,
      seo_description: spec.seoDescription,
      created_at: new Date().toISOString(),
      updated_at: new Date().toISOString(),
    };

    dbProducts.push(prodRecord);

    for (const img of productImages) {
      dbImages.push({
        id: img.id,
        product_id: pId,
        image_url: img.image_url,
        alt_text: img.alt_text,
        sort_order: img.sort_order,
        is_primary: img.is_primary,
        created_at: img.created_at,
      });
    }

    fullProductsForLocal.push({
      ...prodRecord,
      category: {
        id: cat.id,
        name: cat.name,
        slug: cat.slug,
        description: cat.description,
        image_url: cat.image_url,
        parent_id: null,
        sort_order: cat.sort_order,
        is_active: true,
        created_at: new Date().toISOString(),
        updated_at: new Date().toISOString(),
      },
      images: productImages,
    });

    pCounter++;
  }

  // Insert products in chunks
  console.log(`Inserting ${dbProducts.length} products into Supabase...`);
  const chunkSize = 30;
  for (let i = 0; i < dbProducts.length; i += chunkSize) {
    const chunk = dbProducts.slice(i, i + chunkSize);
    const { error: pErr } = await supabase.from("products").insert(chunk);
    if (pErr) {
      console.error(`❌ Error inserting products chunk ${i}:`, pErr);
      process.exit(1);
    }
  }
  console.log(`✅ All ${dbProducts.length} products inserted.`);

  // Insert images in chunks
  console.log(`Inserting ${dbImages.length} product images into Supabase...`);
  for (let i = 0; i < dbImages.length; i += chunkSize) {
    const chunk = dbImages.slice(i, i + chunkSize);
    const { error: imgErr } = await supabase.from("product_images").insert(chunk);
    if (imgErr) {
      console.error(`❌ Error inserting images chunk ${i}:`, imgErr);
      process.exit(1);
    }
  }
  console.log(`✅ All ${dbImages.length} images (4 per product) inserted.`);

  console.log("\n🎉 Catalog Seed Complete! Total Products: 90. Total Images: 360.");
}

runSeed();
